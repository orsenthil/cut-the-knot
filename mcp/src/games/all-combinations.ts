/*
 * run_game_logic actions and saved-position reader for All Combinations.
 * The core (all-combinations/ in the site, copied into src/generated/cores/ at
 * build time) knows the lexicographic enumeration and the binomial count. See
 * _shared.ts for the shape of a game module.
 */

import { cores } from "../generated/cores.js";
import { num, type GameActions, type Json } from "./_shared.js";

const core = () => cores["all-combinations"].AllCombinationsCore;

function readBoard(args: Json): { n: number; m: number } {
  const C = core();
  const n = num(args, "n", 5);
  const m = num(args, "m", 3);
  if (!Number.isInteger(n) || n < C.MIN_N || n > C.MAX_N) throw new Error(`n must be ${C.MIN_N} to ${C.MAX_N}`);
  if (!Number.isInteger(m) || m < C.MIN_M || m > C.MAX_M) throw new Error(`m must be ${C.MIN_M} to ${C.MAX_M}`);
  return { n, m: Math.min(m, n) };
}

export function actions(): GameActions {
  return {
    count_combinations: {
      describe:
        "For N objects chosen M at a time, report the binomial coefficient and check the symmetry and Pascal identities around it.",
      args: '{ "n": 5, "m": 3 }',
      run: (args) => {
        const C = core();
        const { n, m } = readBoard(args);
        const total = C.count(n, m);
        return {
          n,
          m,
          total: total.toString(),
          symmetric: total === C.count(n, n - m),
          pascalNext: m < n ? (total + C.count(n, m + 1)).toString() : null,
          pascalTotal: m < n ? C.count(n + 1, m + 1).toString() : null,
          note: `C(${n}, ${m}) counts the rows in the list.`,
        };
      },
    },
    list_combinations: {
      describe:
        "List the first few combinations in the applet's lexicographic order, as numbers 1..N, with the total number of rows.",
      args: '{ "n": 5, "m": 3, "limit": 10 }',
      run: (args) => {
        const C = core();
        const { n, m } = readBoard(args);
        const limit = Math.min(100, Number.isFinite(args.limit) ? num(args, "limit") : 10);
        let position = C.start({ n, m });
        const rows = [];
        while (C.hasMore(position) && rows.length < limit) {
          position = C.nextState(position);
          rows.push(C.display(position.current));
        }
        return {
          n,
          m,
          total: C.count(n, m).toString(),
          rows: rows.map((r) => r.join(" ")),
          shown: rows.length,
          note: "Rows are generated by advancing the rightmost position with room, then fixing the ones after it.",
        };
      },
    },
  };
}

/** What the core says about a saved list position. */
export function position(state: Json): unknown {
  const C = core();
  const n = num(state, "n", 5);
  const m = num(state, "m", 3);
  const start = C.start({ n, m });
  return {
    n: start.n,
    m: start.m,
    total: C.count(start.n, start.m).toString(),
    firstRow: C.display(start.current),
    note: `C(${start.n}, ${start.m}) combinations, listed from smallest to largest.`,
  };
}
