"use strict";

/*
 * Combi Gem — Alexander Bogomolny's applet "CombiGem" (cut-the-knot.org).
 *
 * The applet is a little laboratory for a theorem of Erdős and Selfridge.
 * You edit a multiset A of whole numbers (start: 1, 2, 3, 4) and it prints the
 * multiset A_s of all sums of s of its members. Two copies on the original page
 * let you hunt for different collections A and B with the same list of sums.
 * The theorem says this can only happen when A and B have the same size n and
 * n is a power of two; the proof uses the generating function f(x) = Σ x^aᵢ.
 *
 * The key idea in the code is that A_s is generated by s nested scans over the
 * indices of A: every s-tuple is used except the ones whose indices are all
 * equal (those are the "x^{s aᵢ}" terms, not the cross terms). With Economize
 * on, tuples that differ only by the order of their indices are counted once —
 * the applet's FormHash sorts the indices and uses that as a dictionary key.
 * With it off, every ordering is kept, so pairs appear twice, etc.
 *
 * This file is the game's logic and nothing else: no document, no window,
 * no storage. It defines one global, CombiGemCore, so the page loads it with a
 * plain <script> and porting/check-combi-gem.mjs loads it in Node. The position
 * is plain data (numbers, arrays, flags), so it can be saved and handed to the
 * tutor as it is. Functions take a position and return a new one; they do not
 * change what they are given.
 */
const CombiGemCore = (() => {
  // The applet's own constants, read from its bytecode: CombiGemPanel sets
  // CTKNumberCanvas.SetRange(2, 9) for "Set size" and (2, 5) for "#summonds",
  // and CombiGemCanvas.init() calls SetCollectionSize(4) with NSummonds = 2.
  const MIN_SIZE = 2;
  const MAX_SIZE = 9;
  const MIN_SUMMONDS = 2;
  const MAX_SUMMONDS = 5;
  const DEFAULT_POOL = [1, 2, 3, 4];
  const SUBSCRIPTS = ["", "", "A₂", "A₃", "A₄", "A₅"];

  /** Java's (int) of a number: truncate, and fall back on a bad value. */
  function asInteger(value, fallback) {
    const n = Math.trunc(Number(value));
    return Number.isFinite(n) ? n : fallback;
  }

  /** asInteger, but inside the applet's [lo, hi] control range. */
  function clampInt(value, lo, hi, fallback) {
    const n = asInteger(value, fallback);
    return Math.min(hi, Math.max(lo, n));
  }

  /**
   * FormHash(int[]) from ComputeSums: sort the indices, then write each one
   * followed by "0". Used as a Hashtable key so cyclic orders of the same
   * tuple are shown only once.
   */
  function formHash(indices) {
    return indices.slice().sort((a, b) => a - b).map((x) => x + "0").join("");
  }

  /**
   * ComputeSums.Compute(N, nums) as a pure function: the multiset A_s, sorted
   * in the nondecreasing order the applet prints, with multiplicity kept.
   * `economize` is the applet's Economize check box (on by default).
   */
  function computeSums(nums, s, economize) {
    const N = nums.length;
    const summonds = clampInt(s, MIN_SUMMONDS, MAX_SUMMONDS, 2);
    const out = [];
    const seen = new Set();
    const idxs = [];

    function visit(depth) {
      if (depth === summonds) {
        // Compute3/4/5 skip only the tuple with every index equal; for s = 2
        // Compute2's Economize branch loops i < j, which is the same thing.
        let allEqual = true;
        for (let k = 1; k < idxs.length; k++) {
          if (idxs[k] !== idxs[0]) { allEqual = false; break; }
        }
        if (allEqual) return;

        let sum = 0;
        for (const ix of idxs) sum += nums[ix];
        if (economize) {
          const key = formHash(idxs);
          if (seen.has(key)) return;
          seen.add(key);
        }
        out.push(sum);
        return;
      }
      for (let i = 0; i < N; i++) {
        idxs.push(i);
        visit(depth + 1);
        idxs.pop();
      }
    }
    visit(0);
    out.sort((a, b) => a - b);
    return out;
  }

  /** The sums of the *visible* numbers of a position. */
  function sums(state) {
    if (!state) return [];
    return computeSums(state.nums.slice(0, state.n), state.s, state.economize);
  }

  /** The position a new game starts from. */
  function start(options) {
    const o = options || {};
    const pool = Array.isArray(o.nums)
      ? o.nums.map((x) => asInteger(x, 1))
      : DEFAULT_POOL.slice();
    // SpreadNumCollection.SetNumsToDisplay grows the pool with 1, 2, 3, ...
    // and never throws old entries away; shrinking only hides them. Keeping
    // the whole pool preserves that harmless quirk of the applet.
    const n = clampInt(o.size === undefined ? pool.length : o.size, MIN_SIZE, MAX_SIZE, DEFAULT_POOL.length);
    while (pool.length < n) pool.push(pool.length + 1);
    return {
      nums: pool,
      n,
      s: clampInt(o.s === undefined ? o.summonds : o.s, MIN_SUMMONDS, MAX_SUMMONDS, 2),
      economize: o.economize === undefined ? true : !!o.economize,
    };
  }

  /** The moves allowed from this position (a demo: the same set throughout). */
  function legalMoves(state) {
    return ["setNumber", "setSize", "setSummonds", "setEconomize", "reset"];
  }

  /** The position after a move, or null if the move is not allowed. */
  function move(state, m) {
    if (!state || !m || typeof m.type !== "string") return null;
    switch (m.type) {
      case "setNumber": {
        const i = m.index;
        if (!Number.isInteger(i) || i < 0 || i >= state.n) return null;
        const nums = state.nums.slice();
        // CTKNumber.UpdateSlow changes a tapped number by exactly one.
        nums[i] = m.value === undefined
          ? nums[i] + asInteger(m.delta, 1)
          : asInteger(m.value, nums[i]);
        return Object.assign({}, state, { nums });
      }
      case "setSize": {
        const n = clampInt(m.size, MIN_SIZE, MAX_SIZE, state.n);
        const nums = state.nums.slice();
        while (nums.length < n) nums.push(nums.length + 1);
        return Object.assign({}, state, { nums, n });
      }
      case "setSummonds": {
        const s = clampInt(m.s === undefined ? m.summonds : m.s, MIN_SUMMONDS, MAX_SUMMONDS, state.s);
        return Object.assign({}, state, { s });
      }
      case "setEconomize": {
        const value = m.value === undefined ? !state.economize : !!m.value;
        return Object.assign({}, state, { economize: value });
      }
      case "reset":
        return start({});
      default:
        return null;
    }
  }

  /** A demo never wins or loses; exploring it is its own end. */
  function result(state) {
    return null;
  }

  /** The number of unordered pairs, C(k, 2), used in the page's first claim. */
  function pairCount(k) {
    return (k * (k - 1)) / 2;
  }

  function isPowerOfTwo(n) {
    return Number.isInteger(n) && n >= 1 && (n & (n - 1)) === 0;
  }

  /**
   * Everything the page needs to show, and the plain position for Track.state:
   * the sums, their count, and one sentence saying what changed in words.
   */
  function describe(state) {
    const list = sums(state);
    const label = SUBSCRIPTS[state.s] || `A^${state.s}`;
    const shown = list.slice(0, 20).join(", ") + (list.length > 20 ? ", …" : "");
    const text = `A = {${state.nums.slice(0, state.n).join(", ")}}. ` +
      `${label} has ${list.length} ${list.length === 1 ? "sum" : "sums"}: ${shown}.`;
    return {
      sums: list,
      count: list.length,
      distinct: new Set(list).size,
      text,
    };
  }

  return {
    MIN_SIZE, MAX_SIZE, MIN_SUMMONDS, MAX_SUMMONDS, DEFAULT_POOL,
    asInteger, clampInt, formHash,
    computeSums, sums, start, legalMoves, move, result,
    pairCount, isPowerOfTwo, describe,
  };
})();
