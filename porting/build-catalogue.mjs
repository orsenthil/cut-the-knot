#!/usr/bin/env node
"use strict";

/*
 * Builds the catalogue, assets/games.js, from each game's own meta.json.
 *
 *   node porting/build-catalogue.mjs           write assets/games.js
 *   node porting/build-catalogue.mjs --check   exit 1 if it is out of date
 *
 * A game is described in its own folder, <slug>/meta.json:
 *
 *   {
 *     "title": "Coins in a Row",
 *     "blurb": "One or two sentences that pose the challenge.",
 *     "tags": ["game-strategy", "parity"],     at most 3, from assets/concepts.js
 *     "level": 2,                              1 (start here) to 3
 *     "kind": "demo",                          only for something with no win or loss
 *     "order": 40                              position on the home page
 *   }
 *
 * so adding a game touches only that game's folder, and two ports made at
 * the same time do not collide. assets/games.js is generated: if two
 * branches both changed it, run this again rather than merging by hand.
 *
 * The tag labels come from assets/concepts.js, the one place a tag is
 * defined. Games are listed by "order", then by slug; a new game takes any
 * number larger than the last.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(REPO, "assets", "games.js");
const KEYS = ["title", "blurb", "tags", "level", "kind", "order"];

function readConcepts() {
  const window = {};
  new Function("window", readFileSync(join(REPO, "assets", "concepts.js"), "utf8"))(window);
  return window.COOLMATHS_CONCEPTS;
}

const concepts = readConcepts();
const problems = [];
const games = [];

for (const entry of readdirSync(REPO, { withFileTypes: true })) {
  const file = join(REPO, entry.name, "meta.json");
  if (!entry.isDirectory() || !existsSync(file)) continue;
  const slug = entry.name;
  const bad = (message) => problems.push(`${slug}/meta.json: ${message}`);

  let meta;
  try {
    meta = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    bad(`not valid JSON (${err.message})`);
    continue;
  }

  for (const key of Object.keys(meta)) if (!KEYS.includes(key)) bad(`unknown field "${key}"`);
  if (typeof meta.title !== "string" || !meta.title.trim()) bad("needs a title");
  if (typeof meta.blurb !== "string" || !meta.blurb.trim()) bad("needs a blurb");
  if (!Array.isArray(meta.tags) || meta.tags.length < 1 || meta.tags.length > 3) bad("needs 1 to 3 tags");
  for (const tag of meta.tags || []) {
    if (!(tag in concepts)) bad(`tag "${tag}" is not defined in assets/concepts.js`);
  }
  if (![1, 2, 3].includes(meta.level)) bad("level must be 1, 2 or 3");
  if (meta.kind !== undefined && meta.kind !== "demo") bad('kind, when given, must be "demo"');
  if (!Number.isFinite(meta.order)) bad("needs a numeric order");
  if (!existsSync(join(REPO, slug, "index.html"))) bad("the folder has no index.html");

  games.push({ slug, ...meta });
}

if (problems.length) {
  for (const p of problems) console.error(p);
  process.exit(1);
}

games.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));

/* ------------------------------------------------------------------ output */

const q = JSON.stringify;
const tagLines = Object.entries(concepts).map(([tag, c]) => `    ${q(tag)}: ${q(c.label)},`);
const gameBlocks = games.map((g) =>
  [
    "    {",
    `      slug: ${q(g.slug)},`,
    `      title: ${q(g.title)},`,
    `      blurb: ${q(g.blurb)},`,
    `      tags: [${g.tags.map(q).join(", ")}],`,
    ...(g.kind ? [`      kind: ${q(g.kind)},`] : []),
    `      level: ${g.level},`,
    "    },",
  ].join("\n"),
);

const output = `"use strict";

/*
 * GENERATED by porting/build-catalogue.mjs. Do not edit.
 * To change a game, edit <slug>/meta.json; to change a tag, edit
 * assets/concepts.js; then run: node porting/build-catalogue.mjs
 *
 * The catalogue of games. The home page builds its grid and tag filter from
 * this list, and each game page shows its own concept tags from it (matched by
 * the <body data-game="..."> slug, which is also the game's folder name).
 * Tags are URL-friendly slugs, so /#number-theory lists every game with that tag.
 *
 *   level  1 (anyone can start here) to 3 (needs patience or earlier ideas)
 *   kind   "demo" for something to explore, with no win or loss
 */

window.COOLMATHS = {
  tags: {
${tagLines.join("\n")}
  },

  games: [
${gameBlocks.join("\n")}
  ],
};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== output) {
    console.error("assets/games.js is out of date. Run: node porting/build-catalogue.mjs");
    process.exit(1);
  }
  console.log(`catalogue up to date (${games.length} games, ${tagLines.length} tags)`);
} else {
  writeFileSync(OUT, output);
  console.log(`wrote assets/games.js (${games.length} games, ${tagLines.length} tags)`);
}
